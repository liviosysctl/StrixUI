/// Every shape of a Lucide icon as one SVG path string (QtQuick.Shapes PathSvg reads it)
pub fn svg_to_path(inner: &str) -> String {
    let shape = Regex::new(r"<(path|circle|line|polyline|polygon|rect|ellipse)\b([^>]*)/?>")
        .expect("regex");
    let attr = Regex::new(r#"([a-z-]+)="([^"]*)""#).expect("regex");
    let rel = Regex::new(r"(?s)^m\s*(-?(?:\d+\.?\d*|\.\d+))[\s,]*(-?(?:\d+\.?\d*|\.\d+))\s*(.*)$")
        .expect("regex");
    let nums = Regex::new(r"-?[\d.]+").expect("regex");
    let mut out = Vec::new();
    for m in shape.captures_iter(inner) {
        let kind = &m[1];
        let attrs: Vec<(String, String)> = attr
            .captures_iter(&m[2])
            .map(|a| (a[1].to_string(), a[2].to_string()))
            .collect();
        let get = |k: &str| {
            attrs
                .iter()
                .rev()
                .find(|(n, _)| n == k)
                .map(|(_, v)| v.clone())
        };
        let g = |k: &str| {
            get(k)
                .map(|v| v.parse::<f64>().expect("a number"))
                .unwrap_or(0.0)
        };
        match kind {
            "path" => {
                let mut d = get("d").expect("d").trim().to_string();
                if let Some(c) = rel.captures(&d.clone()) {
                    let rest = &c[3];
                    let tail = if !rest.is_empty()
                        && !rest.chars().next().expect("a char").is_alphabetic()
                    {
                        format!("l{rest}")
                    } else {
                        rest.to_string()
                    };
                    d = format!("M{} {}{tail}", &c[1], &c[2]);
                }
                out.push(d);
            }
            "circle" | "ellipse" => {
                let (cx, cy) = (g("cx"), g("cy"));
                let (rx, ry) = if kind == "circle" {
                    (g("r"), g("r"))
                } else {
                    (g("rx"), g("ry"))
                };
                let p = py::g;
                out.push(format!(
                    "M{} {}A{} {} 0 1 0 {} {}A{} {} 0 1 0 {} {}Z",
                    p(cx - rx),
                    p(cy),
                    p(rx),
                    p(ry),
                    p(cx + rx),
                    p(cy),
                    p(rx),
                    p(ry),
                    p(cx - rx),
                    p(cy)
                ));
            }
            "line" => out.push(format!(
                "M{} {}L{} {}",
                py::g(g("x1")),
                py::g(g("y1")),
                py::g(g("x2")),
                py::g(g("y2"))
            )),
            "polyline" | "polygon" => {
                let points = get("points").expect("points");
                let pts: Vec<&str> = nums.find_iter(&points).map(|m| m.as_str()).collect();
                let pairs: Vec<String> = pts
                    .chunks(2)
                    .map(|p| format!("{} {}", p[0], p[1]))
                    .collect();
                out.push(format!(
                    "M{}{}",
                    pairs.join("L"),
                    if kind == "polygon" { "Z" } else { "" }
                ));
            }
            "rect" => {
                let (x, y, w, h) = (g("x"), g("y"), g("width"), g("height"));
                let rx = get("rx")
                    .or_else(|| get("ry"))
                    .map(|v| v.parse::<f64>().expect("a number"))
                    .unwrap_or(0.0);
                let ry = get("ry")
                    .or_else(|| get("rx"))
                    .map(|v| v.parse::<f64>().expect("a number"))
                    .unwrap_or(0.0);
                let p = py::g;
                if rx != 0.0 || ry != 0.0 {
                    out.push(format!(
                        "M{} {}H{}A{} {} 0 0 1 {} {}V{}A{} {} 0 0 1 {} {}H{}A{} {} 0 0 1 {} {}V{}A{} {} 0 0 1 {} {}Z",
                        p(x + rx), p(y), p(x + w - rx), p(rx), p(ry), p(x + w), p(y + ry), p(y + h - ry), p(rx), p(ry),
                        p(x + w - rx), p(y + h), p(x + rx), p(rx), p(ry), p(x), p(y + h - ry), p(y + ry), p(rx), p(ry), p(x + rx), p(y)
                    ));
                } else {
                    out.push(format!(
                        "M{} {}H{}V{}H{}Z",
                        p(x),
                        p(y),
                        p(x + w),
                        p(y + h),
                        p(x)
                    ));
                }
            }
            _ => {}
        }
    }
    out.join(" ")
}

fn icons_qml(icons: &[(String, String)]) -> String {
    let mut sorted: Vec<&(String, String)> = icons.iter().collect();
    sorted.sort_by(|a, b| a.0.cmp(&b.0));
    let entries: Vec<String> = sorted
        .iter()
        .map(|(n, s)| format!("        {}: {}", py::quote(n), py::quote(&svg_to_path(s))))
        .collect();
    format!(
        "// The Lucide symbols in use (ISC), each as one path on a 24 by 24 grid. {GENERATED}\npragma Singleton\nimport QtQuick\n\nQtObject {{\n    readonly property var paths: ({{\n{}\n    }})\n\n    function path(name) {{\n        return paths[name] || \"\"\n    }}\n}}\n",
        entries.join(",\n")
    )
}

fn theme_qml(
    src: &Src,
    t: &Value,
    tables: &[(String, Table)],
    gods: &Gods,
    plates: &[(String, String)],
) -> String {
    let all: Vec<&Value> = t["color"]["tokens"]
        .as_array()
        .expect("tokens")
        .iter()
        .collect();
    let names: Vec<&str> = all
        .iter()
        .map(|x| x["name"].as_str().expect("name"))
        .filter(|n| !n.starts_with("term-"))
        .collect();
    let order: Vec<Value> = gods
        .gods
        .iter()
        .map(|g| Value::String(g.id.clone()))
        .collect();
    let tab = |id: &str| &tables.iter().find(|(g, _)| g == id).expect("a table").1;
    let themes: Vec<String> = gods
        .gods
        .iter()
        .map(|g| {
            let pairs: Vec<String> = names
                .iter()
                .map(|n| format!("{}: \"{}\"", py::quote(n), tab(&g.id).c(n)))
                .collect();
            format!("        {}: {{ {} }}", g.id, pairs.join(", "))
        })
        .collect();
    let terms: Vec<String> = gods
        .gods
        .iter()
        .map(|g| {
            let pairs: Vec<String> = TERMINAL
                .iter()
                .map(|n| format!("{}: \"{}\"", py::quote(n), tab(&g.id).t(n)))
                .collect();
            format!("        {}: {{ {} }}", g.id, pairs.join(", "))
        })
        .collect();
    let info: Vec<String> = gods
        .gods
        .iter()
        .map(|g| {
            let plate = &plates
                .iter()
                .find(|(id, _)| *id == g.id)
                .expect("a plate")
                .1;
            format!(
                "        {}: {{ name: {}, description: {}, wallpaper: \"{}.jpg\", plate: {} }}",
                g.id,
                py::quote(&g.name),
                py::quote(&g.description),
                g.id,
                py::quote(plate)
            )
        })
        .collect();
    let colours: Vec<String> = names
        .iter()
        .map(|n| {
            format!(
                "    readonly property color {}: css(c[{}])",
                camel(n),
                py::quote(n)
            )
        })
        .collect();
    let term: Vec<String> = TERMINAL
        .iter()
        .map(|n| {
            format!(
                "    readonly property color {}: css(tc[{}])",
                camel(&format!("term-{n}")),
                py::quote(n)
            )
        })
        .collect();
    let mut dims = Vec::new();
    for group in ["spacing", "radius", "line", "size"] {
        for (name, value, usage) in tok(t, group) {
            dims.push(format!(
                "    readonly property int {}: {}  // {usage}",
                camel(&name),
                px(&value) as i64
            ));
        }
    }
    let mut durs = Vec::new();
    for (name, value, usage) in tok(t, "duration") {
        let ms = duration_ms(&s(&value));
        if name == "theme-cycle" {
            durs.push(format!(
                "    readonly property int themeCycle: {ms}  // {usage}"
            ));
        } else {
            durs.push(format!(
                "    readonly property int {}: reducedMotion ? 1 : {ms}  // {usage}",
                camel(&name)
            ));
        }
    }
    let eases: Vec<String> = tok(t, "easing")
        .into_iter()
        .map(|(name, value, usage)| {
            let nums: Vec<String> = bezier(&s(&value)).into_iter().map(py::g).collect();
            format!(
                "    readonly property var {}: [{}, 1, 1]  // {usage}",
                camel(&name),
                nums.join(", ")
            )
        })
        .collect();
    let opac: Vec<String> = tok(t, "opacity")
        .into_iter()
        .map(|(n, v, u)| {
            format!(
                "    readonly property real {}: {}  // {u}",
                camel(&n),
                s(&v)
            )
        })
        .collect();
    let family = |f: &str| FAMILY.iter().find(|(k, _)| *k == f).expect("a family").1;
    let styles: Vec<String> = text_styles(t)
        .iter()
        .map(|st| {
            format!(
                "        {}: {{ family: {}, pixelSize: {}, lineHeight: {}, weight: {}, italic: {}, letterSpacing: {} }}",
                py::quote(&st.name),
                py::quote(family(&st.family)),
                py::g(st.size),
                py::g(py::round(st.line, 2)),
                st.weight,
                st.italic,
                py::g(st.spacing)
            )
        })
        .collect();
    let palette: Vec<Value> = TERMINAL[4..]
        .iter()
        .map(|n| Value::String((*n).into()))
        .collect();
    // Every font file the tokens name, so the module loads exactly what the design system ships
    let fonts: Vec<String> = t["type"]["fonts"]
        .as_array()
        .expect("fonts")
        .iter()
        .map(|f| {
            format!(
                "        FontLoader {{ source: \"{}\" }}",
                f["file"].as_str().expect("file")
            )
        })
        .collect();
    let fills = [
        ("generated", GENERATED.to_string()),
        ("order", py::json(&Value::Array(order), None)),
        ("themes", themes.join(",\n")),
        ("terms", terms.join(",\n")),
        ("info", info.join(",\n")),
        ("colours", colours.join("\n")),
        ("term", term.join("\n")),
        ("dims", dims.join("\n")),
        ("durs", durs.join("\n")),
        ("eases", eases.join("\n")),
        ("opac", opac.join("\n")),
        ("styles", styles.join(",\n")),
        ("palette", py::json(&Value::Array(palette), None)),
        ("default", gods.gods[0].id.clone()),
        ("fonts", fonts.join(",\n")),
        ("sans", family("sans").into()),
        ("serif", family("serif").into()),
        ("mono", family("mono").into()),
    ];
    // One pass, so a filled value is never read as a placeholder
    let re = Regex::new(r"\{\{(\w+)\}\}").expect("regex");
    let template = read(&src.root.join("templates/Theme.qml"));
    re.replace_all(&template, |c: &regex::Captures| {
        fills
            .iter()
            .find(|(k, _)| *k == &c[1])
            .map(|(_, v)| v.clone())
            .unwrap_or_else(|| panic!("no value for {}", &c[1]))
    })
    .into_owned()
}

fn write_qml(
    src: &Src,
    out: &Path,
    t: &Value,
    tables: &[(String, Table)],
    gods: &Gods,
    plates: &[(String, String)],
    icons: &[(String, String)],
) {
    let d = out.join("qml");
    copy_tree(&src.root.join("qml"), &d);
    let m = d.join("Strix");
    write(
        &m.join("Theme.qml"),
        &theme_qml(src, t, tables, gods, plates),
    );
    write(&m.join("Icons.qml"), &icons_qml(icons));
    for f in crate::site::sorted(&src.root.join("fonts")) {
        if f.ends_with(".woff2") {
            fs::create_dir_all(m.join("fonts")).expect("fonts");
            fs::copy(src.root.join("fonts").join(&f), m.join("fonts").join(&f)).expect("a font");
        }
    }
}

pub fn write_all(
    src: &Src,
    out: &Path,
    t: &Value,
    gods: &Gods,
    plates: &[(String, String)],
    hotkeys: &Value,
    icons: &[(String, String)],
) {
    let first = gods.gods[0].id.clone();
    let tables: Vec<(String, Table)> = gods
        .gods
        .iter()
        .map(|g| (g.id.clone(), table(t, &g.id, &first)))
        .collect();
    write_rust(src, out, t, &tables, gods, plates, hotkeys);
    write_theme_toml(src, out, &tables, gods);
    write_qml(src, out, t, &tables, gods, plates, icons);
}

pub fn copy_tree(from: &Path, to: &Path) {
    fs::create_dir_all(to).expect("a folder");
    for entry in fs::read_dir(from)
        .unwrap_or_else(|e| panic!("cannot read {}: {e}", from.display()))
        .flatten()
    {
        let path = entry.path();
        let target = to.join(entry.file_name());
        if path.is_dir() {
            copy_tree(&path, &target);
        } else {
            fs::copy(&path, &target).expect("a file");
        }
    }
}
