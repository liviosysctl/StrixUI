fn write_rust(
    src: &Src,
    out: &Path,
    t: &Value,
    tables: &[(String, Table)],
    gods: &Gods,
    plates: &[(String, String)],
    hotkeys: &Value,
) {
    let d = out.join("rust/strix-design");
    copy_tree(&src.root.join("rust"), &d);
    write(&d.join("src/tokens.rs"), &rust_tokens(t));
    write(
        &d.join("src/themes.rs"),
        &rust_themes(src, t, tables, gods, plates),
    );
    write(&d.join("src/hotkeys.rs"), &rust_hotkeys(hotkeys));
    // rustfmt, when it is there, so the generated code reads like the rest; cargo fmt --check stays clean
    let status = std::process::Command::new("rustfmt")
        .args(["--edition", "2024", "--config-path"])
        .arg(d.join("rustfmt.toml"))
        .args(["tokens.rs", "themes.rs", "hotkeys.rs"].map(|f| d.join("src").join(f)))
        .status();
    if let Ok(status) = status {
        assert!(status.success(), "rustfmt failed");
    }
}

// ---------------------------------------------------------------- theme.toml for the theme engine

fn write_theme_toml(src: &Src, out: &Path, tables: &[(String, Table)], gods: &Gods) {
    let plates = crate::read_json(&src.root.join("design/plates.json"));
    for g in &gods.gods {
        let tab = &tables
            .iter()
            .find(|(id, _)| *id == g.id)
            .expect("a table")
            .1;
        let mut o = vec![
            format!("# {}. {}", g.name, g.description),
            format!("# {}", GENERATED.replace("Do not edit.", "Edit src/design/gods.json and build again.")),
            "# The ten required colours carry the same names in the design system; every other token is an extra colour.".into(),
            "format = 1".into(),
            format!("name = \"{}\"", g.name),
            format!("description = {}", py::json_ascii(&Value::String(g.description.clone()))),
            "default-variant = \"dark\"".into(),
            String::new(),
            "[variants.dark]".into(),
            "name = \"Dark\"".into(),
            "appearance = \"dark\"".into(),
            String::new(),
            "[variants.dark.colors]".into(),
        ];
        for n in REQUIRED {
            o.push(format!("{n} = \"{}\"", tab.c(n)));
        }
        o.push("# every other token of the design system, under its own name".into());
        for (n, v) in &tab.colors {
            if !REQUIRED.contains(&n.as_str()) {
                o.push(format!("{n} = \"{v}\""));
            }
        }
        o.push(String::new());
        o.push("[variants.dark.terminal]".into());
        for n in TERMINAL {
            o.push(format!("{n} = \"{}\"", tab.t(n)));
        }
        // The light variant: the god's colours on dark grey grounds, with the light plate
        let light = gods.light(&g.id);
        let lc = |n: &str| {
            light
                .iter()
                .find(|(k, _)| k == n)
                .map_or_else(|| tab.c(n), |(_, v)| v.as_str())
        };
        o.extend(
            [
                "",
                "[variants.light]",
                "name = \"Light\"",
                "appearance = \"dark\"",
                "",
                "[variants.light.colors]",
            ]
            .map(String::from),
        );
        for n in REQUIRED {
            o.push(format!("{n} = \"{}\"", lc(n)));
        }
        for (n, _) in &tab.colors {
            if !REQUIRED.contains(&n.as_str()) {
                o.push(format!("{n} = \"{}\"", lc(n)));
            }
        }
        o.push(String::new());
        o.push("[variants.light.terminal]".into());
        for n in TERMINAL {
            let v = if n == "background" {
                lc("background")
            } else {
                tab.t(n)
            };
            o.push(format!("{n} = \"{v}\""));
        }
        let dir = out.join("themes").join(&g.id);
        write(&dir.join("theme.toml"), &(o.join("\n") + "\n"));
        // The caption of the plate, for every theme that takes this one's picture (strix-theme complete)
        let p = &plates[&g.id];
        let credit = p["credit"].as_str().expect("credit");
        let licence = if credit.ends_with("CC0") {
            "CC0"
        } else {
            "public domain"
        };
        write(
            &dir.join("wallpaper.toml"),
            &crate::pack::wallpaper_toml(p["caption"].as_str().expect("caption"), credit, licence),
        );
    }
    let rows: Vec<String> = gods
        .gods
        .iter()
        .map(|g| format!("| `{}` | {} | {} |", g.id, g.name, g.description))
        .collect();
    write(
        &out.join("themes/README.md"),
        &read(&src.root.join("templates/themes-README.md")).replace("{{rows}}", &rows.join("\n")),
    );
}

