fn rust_tokens(t: &Value) -> String {
    let mut o: Vec<String> = vec![
        format!("//! Every token of the design system that is not a colour. {GENERATED}"),
        String::new(),
        "use std::time::Duration;".into(),
        String::new(),
        "use crate::Color;".into(),
        String::new(),
        format!("pub const VERSION: u32 = {};", t["version"]),
        String::new(),
        "/// Pixels at scale 1.".into(),
        "pub type Px = u16;".into(),
        String::new(),
    ];
    for group in ["spacing", "radius", "line", "size"] {
        for (name, value, usage) in tok(t, group) {
            o.push(doc(&usage));
            o.push(format!(
                "pub const {}: Px = {};",
                ident(&name),
                px(&value) as i64
            ));
        }
        o.push(String::new());
    }
    for (name, value, usage) in tok(t, "duration") {
        let v = s(&value);
        let d = if v.ends_with('s') && !v.ends_with("ms") {
            format!("Duration::from_secs({})", &v[..v.len() - 1])
        } else {
            format!("Duration::from_millis({})", &v[..v.len() - 2])
        };
        o.push(doc(&usage));
        o.push(format!("pub const {}: Duration = {d};", ident(&name)));
    }
    o.extend([
        String::new(),
        "/// A CSS `cubic-bezier()`: x1, y1, x2, y2. QML takes the same four numbers in `easing.bezierCurve`.".into(),
        "#[derive(Clone, Copy, Debug, PartialEq)]".into(),
        "pub struct CubicBezier(pub f32, pub f32, pub f32, pub f32);".into(),
        String::new(),
    ]);
    for (name, value, usage) in tok(t, "easing") {
        let nums: Vec<String> = bezier(&s(&value)).into_iter().map(py::repr).collect();
        o.push(doc(&usage));
        o.push(format!(
            "pub const {}: CubicBezier = CubicBezier({});",
            ident(&name),
            nums.join(", ")
        ));
    }
    o.push(String::new());
    for (name, value, usage) in tok(t, "opacity") {
        o.push(doc(&usage));
        o.push(format!(
            "pub const {}: f32 = {};",
            ident(&name),
            py::repr(s(&value).parse().expect("a number"))
        ));
    }
    o.extend(
        [
            "",
            "/// A drop shadow: offset, blur radius and colour.",
            "#[derive(Clone, Copy, Debug, PartialEq, Eq)]",
            "pub struct Shadow {",
            "    pub x: i16,",
            "    pub y: i16,",
            "    pub blur: Px,",
            "    pub color: Color,",
            "}",
            "",
        ]
        .map(String::from),
    );
    for (name, value, usage) in tok(t, "shadow") {
        if let Some((x, y, blur, [r, g, b, a])) = shadow(&s(&value)) {
            o.push(doc(&usage));
            o.push(format!(
                "pub const {}: Shadow = Shadow {{ x: {x}, y: {y}, blur: {blur}, color: Color::rgba({r}, {g}, {b}, {a}) }};",
                ident(&name)
            ));
        }
    }
    o.extend(
        [
            "",
            "/// The three families. The font files are in `fonts/` of the design system.",
            "#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]",
            "pub enum Family {",
            "    Sans,",
            "    Serif,",
            "    Mono,",
            "}",
            "",
            "impl Family {",
            "    /// The family name as fontconfig, Qt and the browser know it.",
            "    pub const fn name(self) -> &'static str {",
            "        match self {",
        ]
        .map(String::from),
    );
    for (k, v) in FAMILY {
        o.push(format!("            Family::{} => \"{v}\",", capitalize(k)));
    }
    o.extend(
        [
            "        }",
            "    }",
            "}",
            "",
            "/// A text style: family, size and line height in pixels, weight, italic, letter spacing in em.",
            "#[derive(Clone, Copy, Debug, PartialEq)]",
            "pub struct TextStyle {",
            "    pub family: Family,",
            "    pub size: f32,",
            "    pub line_height: f32,",
            "    pub weight: u16,",
            "    pub italic: bool,",
            "    pub letter_spacing: f32,",
            "}",
            "",
            "pub mod text {",
            "    use super::{Family, TextStyle};",
            "",
        ]
        .map(String::from),
    );
    for st in text_styles(t) {
        o.push(format!("    {}", doc(&st.usage).replace('\n', "\n    ")));
        o.push(format!(
            "    pub const {}: TextStyle = TextStyle {{ family: Family::{}, size: {}, line_height: {}, weight: {}, italic: {}, letter_spacing: {} }};",
            ident(&st.name),
            capitalize(&st.family),
            py::repr(st.size),
            py::repr(py::round(st.line, 2)),
            st.weight,
            st.italic,
            py::repr(st.spacing)
        ));
    }
    o.extend(["}".to_string(), String::new()]);
    o.join("\n")
}

fn capitalize(s: &str) -> String {
    let mut c = s.chars();
    match c.next() {
        Some(f) => f.to_uppercase().collect::<String>() + &c.as_str().to_lowercase(),
        None => String::new(),
    }
}

fn rust_themes(
    src: &Src,
    t: &Value,
    tables: &[(String, Table)],
    gods: &Gods,
    plates: &[(String, String)],
) -> String {
    let all: Vec<&Value> = t["color"]["tokens"]
        .as_array()
        .expect("tokens")
        .iter()
        .collect();
    let names: Vec<&str> = all
        .iter()
        .map(|x| x["name"].as_str().expect("name"))
        .filter(|n| !n.starts_with("term-"))
        .collect();
    let usage = |n: &str| {
        all.iter()
            .find(|x| x["name"] == n)
            .and_then(|x| x["usage"].as_str())
            .expect("usage")
            .to_string()
    };
    let mut o: Vec<String> = [
        &format!("//! The eight god themes. {GENERATED}") as &str,
        "",
        "use crate::Color;",
        "",
        "/// Light or dark, as `appearance` in theme.toml. Every theme has only its dark variant so far.",
        "#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]",
        "pub enum Appearance {",
        "    Light,",
        "    Dark,",
        "}",
        "",
        "/// Every colour token of one theme.",
        "#[derive(Clone, Copy, Debug, PartialEq, Eq)]",
        "pub struct Colors {",
    ]
    .map(String::from)
    .to_vec();
    for n in &names {
        o.push(format!("    {}", doc(&usage(n)).replace('\n', "\n    ")));
        o.push(format!("    pub {}: Color,", snake(n)));
    }
    let quoted = |list: &[&str]| {
        list.iter()
            .map(|n| format!("\"{n}\""))
            .collect::<Vec<_>>()
            .join(", ")
    };
    o.extend([
        "}".into(),
        String::new(),
        "impl Colors {".into(),
        "    /// The token names, as in tokens.json and theme.toml.".into(),
        format!(
            "    pub const NAMES: [&'static str; {}] = [{}];",
            names.len(),
            quoted(&names)
        ),
        String::new(),
        "    /// A colour by its token name.".into(),
        "    pub fn get(&self, name: &str) -> Option<Color> {".into(),
        "        Some(match name {".into(),
    ]);
    for n in &names {
        o.push(format!("            \"{n}\" => self.{},", snake(n)));
    }
    o.extend(
        [
            "            _ => return None,",
            "        })",
            "    }",
            "",
            "    /// Every token with its name, in the order of tokens.json.",
            "    pub fn iter(&self) -> impl Iterator<Item = (&'static str, Color)> + '_ {",
            "        Self::NAMES.iter().map(move |n| (*n, self.get(n).expect(\"every name has a colour\")))",
            "    }",
            "}",
            "",
            "/// The terminal colours of one theme (`terminal` in theme.toml, `term-` in tokens.json).",
            "#[derive(Clone, Copy, Debug, PartialEq, Eq)]",
            "pub struct Terminal {",
        ]
        .map(String::from),
    );
    for n in TERMINAL {
        o.push(format!("    pub {}: Color,", snake(n)));
    }
    o.extend([
        "}".into(),
        String::new(),
        "impl Terminal {".into(),
        format!(
            "    pub const NAMES: [&'static str; {}] = [{}];",
            TERMINAL.len(),
            quoted(&TERMINAL)
        ),
        String::new(),
        "    pub fn get(&self, name: &str) -> Option<Color> {".into(),
        "        Some(match name {".into(),
    ]);
    for n in TERMINAL {
        o.push(format!("            \"{n}\" => self.{},", snake(n)));
    }
    o.extend(
        [
            "            _ => return None,",
            "        })",
            "    }",
            "}",
            "",
            "/// One god: id, name, its wallpaper and every colour.",
            "#[derive(Clone, Copy, Debug, PartialEq, Eq)]",
            "pub struct Theme {",
            "    /// Id as in theme.toml and `data-theme`.",
            "    pub id: &'static str,",
            "    pub name: &'static str,",
            "    pub description: &'static str,",
            "    /// File in `assets/Wallpapers/`.",
            "    pub wallpaper: &'static str,",
            "    /// Caption of the engraving: what it shows and who made it.",
            "    pub plate: &'static str,",
            "    pub appearance: Appearance,",
            "    pub colors: Colors,",
            "    pub terminal: Terminal,",
            "}",
            "",
            "/// The id of the default theme.",
        ]
        .map(String::from),
    );
    o.push(format!(
        "pub const DEFAULT: &str = \"{}\";",
        gods.gods[0].id
    ));
    o.push(String::new());
    o.push("/// Every theme, the default first.".into());
    o.push(format!(
        "pub static THEMES: [Theme; {}] = [",
        gods.gods.len()
    ));
    for g in &gods.gods {
        let tab = &tables
            .iter()
            .find(|(id, _)| *id == g.id)
            .expect("a table")
            .1;
        let plate = &plates
            .iter()
            .find(|(id, _)| *id == g.id)
            .expect("a plate")
            .1;
        o.extend([
            "    Theme {".into(),
            format!("        id: \"{}\",", g.id),
            format!("        name: \"{}\",", g.name),
            format!(
                "        description: {},",
                py::json_ascii(&Value::String(g.description.clone()))
            ),
            format!("        wallpaper: \"{}.jpg\",", g.id),
            format!(
                "        plate: {},",
                py::json_ascii(&Value::String(plate.clone()))
            ),
            "        appearance: Appearance::Dark,".into(),
            "        colors: Colors {".into(),
        ]);
        for n in &names {
            o.push(format!(
                "            {}: {},",
                snake(n),
                rust_color(tab.c(n))
            ));
        }
        o.push("        },".into());
        o.push("        terminal: Terminal {".into());
        for n in TERMINAL {
            o.push(format!(
                "            {}: {},",
                snake(n),
                rust_color(tab.t(n))
            ));
        }
        o.push("        },".into());
        o.push("    },".into());
    }
    o.extend(
        [
            "];",
            "",
            "/// A theme by id.",
            "pub fn theme(id: &str) -> Option<&'static Theme> {",
            "    THEMES.iter().find(|t| t.id == id)",
            "}",
            "",
            "/// The default theme, Saturnus.",
            "pub fn default_theme() -> &'static Theme {",
            "    &THEMES[0]",
            "}",
            "",
        ]
        .map(String::from),
    );
    o.push(read(&src.root.join("templates/theme-tests.rs")));
    o.join("\n")
}

fn rust_hotkeys(hotkeys: &Value) -> String {
    let list = hotkeys.as_array().expect("hotkeys");
    let mut o: Vec<String> = [
        &format!("//! The default hotkeys: the cheat sheet (Super K) and Settings › Hotkeys start from these. {GENERATED}") as &str,
        "",
        "/// Where a hotkey works.",
        "#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]",
        "pub enum Scope {",
        "    /// Anywhere in the session.",
        "    Global,",
        "    /// Only while the theme picker is open.",
        "    ThemePicker,",
        "}",
        "",
        "/// One action with its keys. Keys are written as on the cheat sheet, separated by spaces: \"Super Shift Return\".",
        "/// \"Super 1–9\" stands for nine bindings, \"Super Arrows\" for four.",
        "#[derive(Clone, Copy, Debug, PartialEq, Eq)]",
        "pub struct Hotkey {",
        "    pub id: &'static str,",
        "    pub group: &'static str,",
        "    pub action: &'static str,",
        "    pub keys: &'static str,",
        "    /// What it acts on, the second line on the cheat sheet.",
        "    pub target: &'static str,",
        "    pub scope: Scope,",
        "}",
        "",
        "impl Hotkey {",
        "    /// The keys one by one.",
        "    pub fn key_list(&self) -> impl Iterator<Item = &'static str> {",
        "        self.keys.split(' ')",
        "    }",
        "}",
        "",
    ]
    .map(String::from)
    .to_vec();
    o.push(format!("pub static HOTKEYS: [Hotkey; {}] = [", list.len()));
    for h in list {
        let (g, a, k, w) = (
            s(&h["group"]),
            s(&h["action"]),
            s(&h["keys"]),
            s(&h["target"]),
        );
        let scope = if w == "In the theme picker" {
            "ThemePicker"
        } else {
            "Global"
        };
        o.push(format!(
            "    Hotkey {{ id: \"{}\", group: \"{g}\", action: \"{a}\", keys: \"{k}\", target: {}, scope: Scope::{scope} }},",
            slug(&a),
            py::json_ascii(&Value::String(w.clone()))
        ));
    }
    o.push("];".into());
    o.push(String::new());
    o.push(HOTKEY_TESTS.into());
    o.join("\n")
}

