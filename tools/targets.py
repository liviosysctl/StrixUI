"""Writes the design system for the code that uses it, from the finished tokens.json.

    rust/strix-design/   Rust crate: tokens, themes, cycle, hotkeys (every back end)
    themes/<god>/        theme.toml in format 1 for the theme engine of StrixOS
    qml/Strix/           QML module for Quickshell (the shell and the Linux apps)

Hand-written parts live in src/rust/ and src/qml/; this file adds the generated ones.
"""
import json, os, re, shutil

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'src')

FAMILY = {'mono': 'JetBrains Mono', 'serif': 'IM Fell English', 'fraktur': 'Grenze Gotisch'}
REQUIRED = ['background', 'surface', 'border', 'text', 'text-muted', 'accent', 'on-accent', 'focus', 'error', 'warning']
TERMINAL = ['background', 'foreground', 'cursor', 'selection', 'black', 'red', 'green', 'yellow', 'blue', 'magenta', 'cyan', 'white',
            'bright-black', 'bright-red', 'bright-green', 'bright-yellow', 'bright-blue', 'bright-magenta', 'bright-cyan', 'bright-white']
GENERATED = 'Generated by tools/build.py from tokens.json. Do not edit.'


def px(v):
    return float(v[:-2]) if isinstance(v, str) and v.endswith('px') else float(v)


def theme_table(t, gods):
    """{god: {'colors': {name: hex}, 'terminal': {name: hex}}} with every token resolved for that god."""
    out = {}
    for g in gods:
        colors, term = {}, {}
        for tok in t['color']['tokens']:
            v = tok['value']
            v = v.get(g['id'], v[gods[0]['id']]) if isinstance(v, dict) else v
            if tok['name'].startswith('term-'):
                term[tok['name'][5:]] = v
            else:
                colors[tok['name']] = v
        out[g['id']] = {'colors': colors, 'terminal': term}
    return out


def text_styles(t):
    styles = []
    for grp in t['type']['groups']:
        for s in grp['styles']:
            size = px(s['fontSize'])
            lh = s['lineHeight']
            lh = px(lh) if isinstance(lh, str) else size * float(lh)
            ls = s.get('letterSpacing', '0em')
            styles.append(dict(name=s['name'], family=grp['family'], size=size, line=lh, weight=int(s['fontWeight']),
                               italic=s.get('fontStyle') == 'italic', spacing=float(ls[:-2]) if ls.endswith('em') else 0.0, usage=s['usage']))
    return styles


def tok(t, group):
    return [(x['name'], x['value'], x['usage']) for x in t[group]['tokens']]


def ident(name):
    return re.sub(r'[^A-Za-z0-9]', '_', name).upper()


def snake(name):
    return re.sub(r'[^a-z0-9]', '_', name.lower())


def camel(name):
    parts = re.split(r'[^A-Za-z0-9]', name)
    return parts[0] + ''.join(p[:1].upper() + p[1:] for p in parts[1:])


def slug(text):
    return re.sub(r'[^a-z0-9]+', '-', text.lower()).strip('-')


def doc(text):
    return '\n'.join('/// ' + line for line in text.split('\n'))


def shadow(v):
    m = re.match(r'(-?\d+)(?:px)? (-?\d+)(?:px)? (\d+)px rgba\((\d+), (\d+), (\d+), ([\d.]+)\)', v)
    if not m:
        return None
    x, y, blur, r, g, b, a = m.groups()
    return int(x), int(y), int(blur), (int(r), int(g), int(b), round(float(a) * 255))


def rgb(hexv):
    h = hexv.lstrip('#')
    parts = [int(h[i:i + 2], 16) for i in range(0, len(h), 2)]
    return parts if len(parts) == 4 else parts + [255]


def rust_color(hexv):
    r, g, b, a = rgb(hexv)
    return 'Color::rgba(0x%02x, 0x%02x, 0x%02x, 0x%02x)' % (r, g, b, a) if a != 255 else 'Color::rgb(0x%02x, 0x%02x, 0x%02x)' % (r, g, b)


# ---------------------------------------------------------------- Rust

def rust_tokens(t):
    o = ['//! Every token of the design system that is not a colour. ' + GENERATED, '',
         'use std::time::Duration;', '', 'use crate::Color;', '',
         'pub const VERSION: u32 = %d;' % t['version'], '',
         '/// Pixels at scale 1.', 'pub type Px = u16;', '']
    for group in ['spacing', 'radius', 'line', 'size']:
        for name, value, usage in tok(t, group):
            o += [doc(usage), 'pub const %s: Px = %d;' % (ident(name), px(value))]
        o.append('')
    for name, value, usage in tok(t, 'duration'):
        d = 'Duration::from_secs(%d)' % int(value[:-1]) if value.endswith('s') and not value.endswith('ms') else 'Duration::from_millis(%d)' % int(value[:-2])
        o += [doc(usage), 'pub const %s: Duration = %s;' % (ident(name), d)]
    o += ['', '/// A CSS `cubic-bezier()`: x1, y1, x2, y2. QML takes the same four numbers in `easing.bezierCurve`.',
          '#[derive(Clone, Copy, Debug, PartialEq)]', 'pub struct CubicBezier(pub f32, pub f32, pub f32, pub f32);', '']
    for name, value, usage in tok(t, 'easing'):
        nums = ', '.join('%s' % float(n) for n in re.findall(r'-?[\d.]+', value))
        o += [doc(usage), 'pub const %s: CubicBezier = CubicBezier(%s);' % (ident(name), nums)]
    o.append('')
    for name, value, usage in tok(t, 'opacity'):
        o += [doc(usage), 'pub const %s: f32 = %s;' % (ident(name), float(value))]
    o += ['', '/// A drop shadow: offset, blur radius and colour.', '#[derive(Clone, Copy, Debug, PartialEq, Eq)]',
          'pub struct Shadow {', '    pub x: i16,', '    pub y: i16,', '    pub blur: Px,', '    pub color: Color,', '}', '']
    for name, value, usage in tok(t, 'shadow'):
        s = shadow(value)
        if s:
            o += [doc(usage), 'pub const %s: Shadow = Shadow { x: %d, y: %d, blur: %d, color: Color::rgba(%d, %d, %d, %d) };' % ((ident(name),) + s[:3] + s[3])]
    o += ['', '/// The three families. The font files are in `fonts/` of the design system.',
          '#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]', 'pub enum Family {', '    Mono,', '    Serif,', '    Fraktur,', '}', '',
          'impl Family {', '    /// The family name as fontconfig, Qt and the browser know it.', '    pub const fn name(self) -> &\'static str {', '        match self {']
    for k, v in FAMILY.items():
        o.append('            Family::%s => "%s",' % (k.capitalize(), v))
    o += ['        }', '    }', '}', '',
          '/// A text style: family, size and line height in pixels, weight, italic, letter spacing in em.',
          '#[derive(Clone, Copy, Debug, PartialEq)]', 'pub struct TextStyle {', '    pub family: Family,', '    pub size: f32,', '    pub line_height: f32,',
          '    pub weight: u16,', '    pub italic: bool,', '    pub letter_spacing: f32,', '}', '', 'pub mod text {', '    use super::{Family, TextStyle};', '']
    for s in text_styles(t):
        o += ['    ' + doc(s['usage']).replace('\n', '\n    '),
              '    pub const %s: TextStyle = TextStyle { family: Family::%s, size: %s, line_height: %s, weight: %d, italic: %s, letter_spacing: %s };'
              % (ident(s['name']), s['family'].capitalize(), float(s['size']), round(float(s['line']), 2), s['weight'], str(s['italic']).lower(), s['spacing'])]
    o += ['}', '']
    return '\n'.join(o)


def rust_themes(t, table, gods, plates):
    names = [x['name'] for x in t['color']['tokens'] if not x['name'].startswith('term-')]
    usage = {x['name']: x['usage'] for x in t['color']['tokens']}
    o = ['//! The eight god themes. ' + GENERATED, '', 'use crate::Color;', '',
         '/// Light or dark, as `appearance` in theme.toml. Every theme has only its dark variant so far.',
         '#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]', 'pub enum Appearance {', '    Light,', '    Dark,', '}', '',
         '/// Every colour token of one theme.', '#[derive(Clone, Copy, Debug, PartialEq, Eq)]', 'pub struct Colors {']
    for n in names:
        o += ['    ' + doc(usage[n]).replace('\n', '\n    '), '    pub %s: Color,' % snake(n)]
    o += ['}', '', 'impl Colors {', '    /// The token names, as in tokens.json and theme.toml.', '    pub const NAMES: [&\'static str; %d] = [%s];' % (len(names), ', '.join('"%s"' % n for n in names)), '',
          '    /// A colour by its token name.', '    pub fn get(&self, name: &str) -> Option<Color> {', '        Some(match name {']
    for n in names:
        o.append('            "%s" => self.%s,' % (n, snake(n)))
    o += ['            _ => return None,', '        })', '    }', '', '    /// Every token with its name, in the order of tokens.json.',
          '    pub fn iter(&self) -> impl Iterator<Item = (&\'static str, Color)> + \'_ {',
          '        Self::NAMES.iter().map(move |n| (*n, self.get(n).expect("every name has a colour")))', '    }', '}', '',
          '/// The terminal colours of one theme (`terminal` in theme.toml, `term-` in tokens.json).',
          '#[derive(Clone, Copy, Debug, PartialEq, Eq)]', 'pub struct Terminal {']
    for n in TERMINAL:
        o.append('    pub %s: Color,' % snake(n))
    o += ['}', '', 'impl Terminal {', '    pub const NAMES: [&\'static str; %d] = [%s];' % (len(TERMINAL), ', '.join('"%s"' % n for n in TERMINAL)), '',
          '    pub fn get(&self, name: &str) -> Option<Color> {', '        Some(match name {']
    for n in TERMINAL:
        o.append('            "%s" => self.%s,' % (n, snake(n)))
    o += ['            _ => return None,', '        })', '    }', '}', '',
          '/// One god: id, name, its wallpaper and every colour.', '#[derive(Clone, Copy, Debug, PartialEq, Eq)]', 'pub struct Theme {',
          '    /// Id as in theme.toml and `data-theme`.', '    pub id: &\'static str,', '    pub name: &\'static str,', '    pub description: &\'static str,',
          '    /// File in `assets/Wallpapers/`.', '    pub wallpaper: &\'static str,', '    /// Caption of the engraving: what it shows and who made it.', '    pub plate: &\'static str,',
          '    pub appearance: Appearance,', '    pub colors: Colors,', '    pub terminal: Terminal,', '}', '',
          '/// The id of the default theme.', 'pub const DEFAULT: &str = "%s";' % gods[0]['id'], '',
          '/// Every theme, the default first.', 'pub static THEMES: [Theme; %d] = [' % len(gods)]
    for g in gods:
        c, tm = table[g['id']]['colors'], table[g['id']]['terminal']
        o += ['    Theme {', '        id: "%s",' % g['id'], '        name: "%s",' % g['name'], '        description: %s,' % json.dumps(g['description']),
              '        wallpaper: "%s.jpg",' % g['id'], '        plate: %s,' % json.dumps(plates[g['id']]), '        appearance: Appearance::Dark,', '        colors: Colors {']
        o += ['            %s: %s,' % (snake(n), rust_color(c[n])) for n in names]
        o += ['        },', '        terminal: Terminal {']
        o += ['            %s: %s,' % (snake(n), rust_color(tm[n])) for n in TERMINAL]
        o += ['        },', '    },']
    o += ['];', '', '/// A theme by id.', 'pub fn theme(id: &str) -> Option<&\'static Theme> {', '    THEMES.iter().find(|t| t.id == id)', '}', '',
          '/// The default theme, Saturnus.', 'pub fn default_theme() -> &\'static Theme {', '    &THEMES[0]', '}', '', RUST_THEME_TESTS]
    return '\n'.join(o)


RUST_THEME_TESTS = r'''#[cfg(test)]
mod tests {
    use super::*;

    /// The rules of the theme engine (format 1) and of the design system, for every theme.
    #[test]
    fn every_theme_passes_the_contrast_rules() {
        let mut fails = Vec::new();
        for t in &THEMES {
            let c = &t.colors;
            let mut need = |what: &str, a: Color, b: Color, min: f64| {
                let r = a.contrast(b);
                if r < min {
                    fails.push(format!("{}: {what} {r:.2} < {min}", t.id));
                }
            };
            for (name, ground) in [("background", c.background), ("surface", c.surface), ("surface-raised", c.surface_raised)] {
                need(&format!("text on {name}"), c.text, ground, 4.5);
                need(&format!("text-muted on {name}"), c.text_muted, ground, 4.5);
                need(&format!("accent-text on {name}"), c.accent_text, ground, 4.5);
                need(&format!("error on {name}"), c.error, ground, 4.5);
                need(&format!("focus on {name}"), c.focus, ground, 3.0);
            }
            need("on-accent on accent", c.on_accent, c.accent, 4.5);
            need("on-accent on accent-hover", c.on_accent, c.accent_hover, 4.5);
            need("on-accent on accent-pressed", c.on_accent, c.accent_pressed, 4.5);
            need("border-strong on surface", c.border_strong, c.surface, 3.0);
            need("terminal foreground", t.terminal.foreground, t.terminal.background, 4.5);
            assert!(c.text.luminance() > c.background.luminance(), "{} is dark", t.id);
        }
        assert!(fails.is_empty(), "{}", fails.join("\n"));
    }

    #[test]
    fn ids_are_unique_and_the_default_comes_first() {
        assert_eq!(THEMES[0].id, DEFAULT);
        for (i, a) in THEMES.iter().enumerate() {
            assert!(THEMES[i + 1..].iter().all(|b| b.id != a.id), "{} twice", a.id);
            assert_eq!(theme(a.id), Some(a));
        }
        assert_eq!(theme("chamber"), None);
    }

    #[test]
    fn names_reach_every_field() {
        let c = &THEMES[1].colors;
        assert_eq!(c.iter().count(), Colors::NAMES.len());
        assert_eq!(c.get("accent"), Some(c.accent));
        assert_eq!(c.get("nothing"), None);
        assert!(Terminal::NAMES.iter().all(|n| THEMES[1].terminal.get(n).is_some()));
    }
}
'''


def rust_hotkeys(hotkeys):
    o = ['//! The default hotkeys: the cheat sheet (Super K) and Settings › Hotkeys start from these. ' + GENERATED, '',
         '/// Where a hotkey works.', '#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]', 'pub enum Scope {', '    /// Anywhere in the session.', '    Global,',
         '    /// Only while the theme picker is open.', '    ThemePicker,', '}', '',
         '/// One action with its keys. Keys are written as on the cheat sheet, separated by spaces: "Super Shift Return".',
         '/// "Super 1–9" stands for nine bindings, "Super Arrows" for four.',
         '#[derive(Clone, Copy, Debug, PartialEq, Eq)]', 'pub struct Hotkey {', '    pub id: &\'static str,', '    pub group: &\'static str,', '    pub action: &\'static str,',
         '    pub keys: &\'static str,', '    /// What it acts on, the second line on the cheat sheet.', '    pub target: &\'static str,', '    pub scope: Scope,', '}', '',
         'impl Hotkey {', '    /// The keys one by one.', '    pub fn key_list(&self) -> impl Iterator<Item = &\'static str> {', '        self.keys.split(\' \')', '    }', '}', '',
         'pub static HOTKEYS: [Hotkey; %d] = [' % len(hotkeys)]
    for g, a, k, w in hotkeys:
        scope = 'ThemePicker' if w == 'In the theme picker' else 'Global'
        o.append('    Hotkey { id: "%s", group: "%s", action: "%s", keys: "%s", target: %s, scope: Scope::%s },' % (slug(a), g, a, k, json.dumps(w), scope))
    o += ['];', '', r'''#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn no_two_actions_share_keys() {
        for (i, a) in HOTKEYS.iter().enumerate() {
            for b in &HOTKEYS[i + 1..] {
                assert!(a.scope != b.scope || a.keys != b.keys, "{} and {} both use {}", a.action, b.action, a.keys);
                assert_ne!(a.id, b.id);
            }
        }
    }

    #[test]
    fn the_cheat_sheet_has_its_own_key() {
        let sheet = HOTKEYS.iter().find(|h| h.id == "all-hotkeys").expect("cheat sheet");
        assert_eq!(sheet.key_list().collect::<Vec<_>>(), ["Super", "K"]);
    }
}
''']
    return '\n'.join(o)


