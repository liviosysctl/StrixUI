def write_rust(out, t, table, gods, plates, hotkeys):
    d = os.path.join(out, 'rust', 'strix-design')
    shutil.copytree(os.path.join(SRC, 'rust'), d)
    open(os.path.join(d, 'Cargo.toml'), 'w').write(CARGO)
    open(os.path.join(d, 'src', 'tokens.rs'), 'w').write(rust_tokens(t))
    open(os.path.join(d, 'src', 'themes.rs'), 'w').write(rust_themes(t, table, gods, plates))
    open(os.path.join(d, 'src', 'hotkeys.rs'), 'w').write(rust_hotkeys(hotkeys))
    # rustfmt, when it is there, so the generated code reads like the rest; cargo fmt --check stays clean
    fmt = shutil.which('rustfmt')
    if fmt:
        import subprocess
        subprocess.run([fmt, '--edition', '2024', '--config-path', os.path.join(d, 'rustfmt.toml')] +
                       [os.path.join(d, 'src', f) for f in ('tokens.rs', 'themes.rs', 'hotkeys.rs')], check=True)


# ---------------------------------------------------------------- theme.toml for the theme engine

def write_theme_toml(out, t, table, gods):
    for g in gods:
        c, tm = table[g['id']]['colors'], table[g['id']]['terminal']
        o = ['# %s. %s' % (g['name'], g['description']),
             '# ' + GENERATED.replace('Do not edit.', 'Edit tools/themes.py and build again.'),
             '# The ten required colours carry the same names in the design system; every other token is an extra colour.',
             'format = 1', 'name = "%s"' % g['name'], 'description = %s' % json.dumps(g['description']), 'default-variant = "dark"', '',
             '[variants.dark]', 'name = "Dark"', 'appearance = "dark"', '', '[variants.dark.colors]']
        o += ['%s = "%s"' % (n, c[n]) for n in REQUIRED]
        o.append('# every other token of the design system, under its own name')
        o += ['%s = "%s"' % (n, v) for n, v in c.items() if n not in REQUIRED]
        o += ['', '[variants.dark.terminal]']
        o += ['%s = "%s"' % (n, tm[n]) for n in TERMINAL]
        p = os.path.join(out, 'themes', g['id'])
        os.makedirs(p, exist_ok=True)
        open(os.path.join(p, 'theme.toml'), 'w').write('\n'.join(o) + '\n')
    rows = '\n'.join('| `%s` | %s | %s |' % (g['id'], g['name'], g['description']) for g in gods)
    open(os.path.join(out, 'themes', 'README.md'), 'w').write(THEMES_README % rows)


THEMES_README = '''# Themes for the theme engine

One folder per god, each with a `theme.toml` in format 1 of the StrixOS theme engine (`themes/README.md` in the strixos repository). Copy the folders into `themes/` there; `saturnus` is the default.

| Id | Name | Colour |
|---|---|---|
%s

- One variant each, `dark`. A light variant follows with the light theme of the design system.
- The ten required colours (`background`, `surface`, `border`, `text`, `text-muted`, `accent`, `on-accent`, `focus`, `error`, `warning`) have the same names in the design system. Every other colour token follows as an extra colour under its own name, so the engine passes all of them on in `/run/strix/theme/tokens.json`, where the QML module reads them.
- `terminal` holds the `term-` colours without the prefix.
- The wallpaper is not part of format 1 yet. Until it is, the shell takes `assets/Wallpapers/<id>.jpg`.
'''

# ---------------------------------------------------------------- QML for Quickshell

def write_qml(out, t, table, gods, plates, icon_paths):
    from qml_gen import theme_qml, icons_qml
    d = os.path.join(out, 'qml')
    shutil.copytree(os.path.join(SRC, 'qml'), d)
    m = os.path.join(d, 'Strix')
    open(os.path.join(m, 'Theme.qml'), 'w').write(theme_qml(t, table, gods, plates))
    open(os.path.join(m, 'Icons.qml'), 'w').write(icons_qml(icon_paths))
    fd = os.path.join(m, 'fonts')
    os.makedirs(fd, exist_ok=True)
    for f in sorted(os.listdir(os.path.join(SRC, 'fonts'))):
        if f.endswith('.woff2'):
            shutil.copy(os.path.join(SRC, 'fonts', f), os.path.join(fd, f))


def write_all(out, t, gods, plates, hotkeys, icon_paths):
    table = theme_table(t, gods)
    write_rust(out, t, table, gods, plates, hotkeys)
    write_theme_toml(out, t, table, gods)
    write_qml(out, t, table, gods, plates, icon_paths)
